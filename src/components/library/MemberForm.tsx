import React, { useState, useEffect } from 'react';
import { Member, MemberStatus } from '../../types';
import { Input } from '../ui/Input';
import { Select } from '../ui/Select';
import { Button } from '../ui/Button';
import { Card } from '../ui/Card';
import { Save, ArrowLeft, UserPlus, ShieldAlert, Sparkles, Hash } from 'lucide-react';

export interface MemberFormProps {
  initialData?: Partial<Member>;
  autoGeneratedId?: string;
  isEdit?: boolean;
  onSubmit: (data: {
    name: string;
    email: string;
    phone: string;
    address: string;
    status: MemberStatus;
  }) => { success: boolean; message: string };
  onCancel: () => void;
  existingEmails?: string[];
}

export const MemberForm: React.FC<MemberFormProps> = ({
  initialData,
  autoGeneratedId,
  isEdit = false,
  onSubmit,
  onCancel,
  existingEmails = [],
}) => {
  const [form, setForm] = useState({
    name: initialData?.name || '',
    email: initialData?.email || '',
    phone: initialData?.phone || '',
    address: initialData?.address || '',
    status: (initialData?.status as MemberStatus) || 'Aktif',
  });

  const [errors, setErrors] = useState<Record<string, string>>({});
  const [isSubmitting, setIsSubmitting] = useState(false);

  useEffect(() => {
    if (initialData) {
      setForm({
        name: initialData.name || '',
        email: initialData.email || '',
        phone: initialData.phone || '',
        address: initialData.address || '',
        status: (initialData.status as MemberStatus) || 'Aktif',
      });
    }
  }, [initialData]);

  const validate = () => {
    const errs: Record<string, string> = {};

    // 1. Nama wajib
    if (!form.name.trim()) {
      errs.name = 'Nama lengkap wajib diisi.';
    } else if (form.name.trim().length < 2) {
      errs.name = 'Nama lengkap minimal 2 karakter.';
    }

    // 2. Email wajib & format valid
    const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    if (!form.email.trim()) {
      errs.email = 'Alamat email wajib diisi.';
    } else if (!emailRegex.test(form.email.trim())) {
      errs.email = 'Format alamat email tidak valid (contoh: anggota@email.com).';
    } else {
      // Cek duplikasi email
      const isDuplicate = existingEmails.some(
        (em) =>
          em.toLowerCase() === form.email.trim().toLowerCase() &&
          (!isEdit || em.toLowerCase() !== initialData?.email?.toLowerCase())
      );
      if (isDuplicate) {
        errs.email = `Email "${form.email.trim()}" sudah terdaftar sebagai anggota.`;
      }
    }

    // 3. No. Telepon wajib & format nomor
    const cleanPhone = form.phone.trim().replace(/[\s-]/g, '');
    const phoneRegex = /^[0-9+]{8,18}$/;
    if (!form.phone.trim()) {
      errs.phone = 'Nomor telepon wajib diisi.';
    } else if (!phoneRegex.test(cleanPhone)) {
      errs.phone = 'Format nomor telepon tidak valid (minimal 8-18 digit angka).';
    }

    // 4. Alamat wajib
    if (!form.address.trim()) {
      errs.address = 'Alamat domisili wajib diisi.';
    } else if (form.address.trim().length < 5) {
      errs.address = 'Alamat domisili minimal 5 karakter.';
    }

    setErrors(errs);
    return Object.keys(errs).length === 0;
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (!validate()) return;

    setIsSubmitting(true);
    const result = onSubmit({
      name: form.name.trim(),
      email: form.email.trim().toLowerCase(),
      phone: form.phone.trim(),
      address: form.address.trim(),
      status: form.status,
    });
    setIsSubmitting(false);

    if (!result.success) {
      setErrors((prev) => ({ ...prev, form: result.message }));
    }
  };

  const displayId = isEdit ? initialData?.id : autoGeneratedId || 'MBR-Auto';

  return (
    <Card noPadding className="overflow-hidden border border-slate-200/90 shadow-sm">
      <form onSubmit={handleSubmit}>
        <div className="p-6 sm:p-8 space-y-6">
          {errors.form && (
            <div className="p-3.5 bg-rose-50 border border-rose-200 text-rose-700 text-xs rounded-lg font-medium flex items-center gap-2">
              <ShieldAlert size={16} className="shrink-0 text-rose-600" />
              <span>{errors.form}</span>
            </div>
          )}

          {/* ID Anggota (Auto-generated preview / Readonly) */}
          <div className="flex flex-col gap-1.5">
            <div className="flex items-center justify-between">
              <label className="text-xs font-semibold text-slate-700 flex items-center gap-1.5">
                <Hash size={13} className="text-slate-500" />
                <span>ID Anggota</span>
              </label>
              <span className="text-[11px] font-medium text-slate-500 flex items-center gap-1">
                {isEdit ? (
                  'Identitas unik sistem (tidak dapat diubah)'
                ) : (
                  <>
                    <Sparkles size={11} className="text-indigo-500" />
                    <span>Dibuat otomatis oleh sistem</span>
                  </>
                )}
              </span>
            </div>
            <div className="relative">
              <input
                type="text"
                disabled
                value={displayId}
                className="w-full rounded-lg border border-slate-200 bg-slate-100/80 px-3 py-2 text-sm font-mono font-semibold text-slate-700 cursor-not-allowed select-none"
              />
            </div>
          </div>

          {/* Baris 1: Nama Lengkap */}
          <Input
            label="Nama Lengkap"
            value={form.name}
            onChange={(e) => {
              setForm({ ...form, name: e.target.value });
              if (errors.name) setErrors({ ...errors, name: '' });
            }}
            placeholder="Masukkan nama lengkap anggota sesuai KTP / Kartu Pelajar"
            error={errors.name}
            required
            helperText="Gunakan nama lengkap resmi untuk validasi peminjaman buku"
          />

          {/* Baris 2: Email & No. Telepon */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-5">
            <Input
              label="Alamat Email"
              type="email"
              value={form.email}
              onChange={(e) => {
                setForm({ ...form, email: e.target.value });
                if (errors.email) setErrors({ ...errors, email: '' });
              }}
              placeholder="nama@email.com"
              error={errors.email}
              required
              helperText="Digunakan untuk identifikasi akun anggota"
            />
            <Input
              label="Nomor Telepon / WhatsApp"
              value={form.phone}
              onChange={(e) => {
                setForm({ ...form, phone: e.target.value });
                if (errors.phone) setErrors({ ...errors, phone: '' });
              }}
              placeholder="081234567890"
              error={errors.phone}
              required
              helperText="Nomor kontak aktif untuk konfirmasi peminjaman"
            />
          </div>

          {/* Baris 3: Alamat Domisili */}
          <div className="flex flex-col gap-1.5">
            <div className="flex items-center justify-between">
              <label className="text-xs font-semibold text-slate-700">
                Alamat Domisili <span className="text-rose-500">*</span>
              </label>
              <span className="text-[11px] text-slate-500">Minimal 5 karakter</span>
            </div>
            <textarea
              rows={3}
              value={form.address}
              onChange={(e) => {
                setForm({ ...form, address: e.target.value });
                if (errors.address) setErrors({ ...errors, address: '' });
              }}
              placeholder="Masukkan alamat domisili lengkap anggota..."
              className={`w-full rounded-lg border bg-white p-3 text-sm text-slate-900 transition-colors focus:outline-none focus:ring-2 focus:ring-offset-1 ${
                errors.address
                  ? 'border-rose-400 focus:border-rose-500 focus:ring-rose-200'
                  : 'border-slate-300 focus:border-indigo-500 focus:ring-indigo-100'
              }`}
            />
            {errors.address && (
              <p className="text-xs text-rose-600 font-medium">{errors.address}</p>
            )}
          </div>

          {/* Baris 4: Status Keaktifan */}
          <Select
            label="Status Keaktifan"
            value={form.status}
            onChange={(e) => setForm({ ...form, status: e.target.value as MemberStatus })}
            options={[
              { value: 'Aktif', label: 'Aktif (Dapat melakukan peminjaman buku)' },
              { value: 'Tidak Aktif', label: 'Tidak Aktif (Dibekukan / Tidak dapat meminjam)' },
            ]}
          />
        </div>

        {/* Footer Actions */}
        <div className="px-6 py-4 bg-slate-50 border-t border-slate-200 flex items-center justify-end gap-2.5">
          <Button variant="outline" type="button" onClick={onCancel}>
            <ArrowLeft size={15} />
            <span>Batal</span>
          </Button>
          <Button
            type="submit"
            isLoading={isSubmitting}
            icon={isEdit ? <Save size={15} /> : <UserPlus size={15} />}
          >
            <span>{isEdit ? 'Simpan Perubahan' : 'Tambah Anggota'}</span>
          </Button>
        </div>
      </form>
    </Card>
  );
};
